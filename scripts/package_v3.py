def strict_json(path):
    def reject(value):
        raise ValidationError("Nonfinite JSON number: " + value)
    return json.loads(Path(path).read_text(encoding="utf-8"), parse_constant=reject)


def file_identity(path):
    path = Path(path)
    if not path.is_file() or path.is_symlink():
        raise ValidationError("Delivery source must be a regular non-symlink file: " + path.name)
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return {"bytes": path.stat().st_size, "sha256": digest.hexdigest()}


def safe_name(name):
    if not isinstance(name, str) or not name or Path(name).name != name or name in {".", ".."} or "/" in name or "\\" in name or ":" in name:
        raise ValidationError("Only flat explicit filenames are allowed in v3 delivery")
    return name


def _material_record(record):
    """Validate one effective native/portable material binding."""
    if not isinstance(record, dict) or not isinstance(record.get("source_material_name"), str) or not record["source_material_name"]:
        raise ValidationError("Every portable binding needs its native source material name")
    color = record.get("base_color_factor")
    if not isinstance(color, (list, tuple)) or len(color) != 4 or any(type(value) not in (int, float) or not math.isfinite(value) or not 0 <= value <= 1 for value in color):
        raise ValidationError("Portable material needs finite linear RGBA in [0,1]")
    scale = record.get("facade_tint_scale", 1)
    if type(scale) not in (int, float) or not math.isfinite(scale) or not 0 <= scale <= 1:
        raise ValidationError("Portable material needs a finite facade tint scale in [0,1]")
    factors = {}
    for field in ("roughness_factor", "metallic_factor"):
        value = record.get(field)
        if type(value) not in (int, float) or not math.isfinite(value) or not 0 <= value <= 1:
            raise ValidationError("Portable material needs a finite " + field + " in [0,1]")
        factors[field] = value
    return {"source_material_name": record["source_material_name"], "base_color_factor": list(color), "facade_tint_scale": scale, **factors}


def _same_material(left, right, tolerance=1e-6):
    return (left["source_material_name"] == right["source_material_name"]
            and abs(left["facade_tint_scale"] - right["facade_tint_scale"]) <= tolerance
            and all(abs(left[field] - right[field]) <= tolerance for field in ("roughness_factor", "metallic_factor"))
            and all(abs(a - b) <= tolerance for a, b in zip(left["base_color_factor"], right["base_color_factor"])))


def _unique_materials(records):
    result = []
    for record in records:
        if not any(_same_material(record, other) for other in result):
            result.append(record)
    return result


def check_material_expectations(expectation):
    bindings = expectation.get("material_bindings")
    if not isinstance(bindings, dict) or not bindings or set(bindings) != set(expectation["object_bounds"]):
        raise ValidationError("Fresh native effective material bindings are required for every GLB mesh")
    checked = {}
    for name, records in bindings.items():
        if not isinstance(records, list) or not records:
            raise ValidationError("Every GLB mesh needs a nonempty material binding inventory: " + name)
        checked[name] = [_material_record(record) for record in records]
        if len(_unique_materials(checked[name])) != len(records):
            raise ValidationError("Expected GLB bindings must list distinct effective source materials: " + name)
    metadata = expectation.get("node_owner_roles")
    if metadata is not None and (not isinstance(metadata, dict) or set(metadata) != set(bindings) or any(not isinstance(record, dict) or set(record) != {"owner", "role"} or any(value is not None and not isinstance(value, str) for value in record.values()) for record in metadata.values())):
        raise ValidationError("Portable owner/role provenance must describe every expected mesh node")
    return checked


def _glb_document(path):
    """Read the actual GLB JSON chunk without loading its geometry into memory."""
    path = Path(path)
    try:
        with path.open("rb") as source:
            header = source.read(12)
            if len(header) != 12:
                raise ValidationError("Portable material check needs a complete GLB header")
            magic, version, length = struct.unpack("<4sII", header)
            chunk_header = source.read(8)
            if len(chunk_header) != 8:
                raise ValidationError("Portable material check needs a GLB JSON chunk")
            chunk_length, chunk_type = struct.unpack("<II", chunk_header)
            if magic != b"glTF" or version != 2 or length != path.stat().st_size or chunk_type != 0x4E4F534A or chunk_length % 4 or chunk_length > length - 20:
                raise ValidationError("Portable material GLB header/JSON chunk differs from actual bytes")
            def reject(value):
                raise ValidationError("Nonfinite portable material JSON number: " + value)
            document = json.loads(source.read(chunk_length).decode("utf-8"), parse_constant=reject)
    except (OSError, ValueError, struct.error, UnicodeError) as error:
        raise ValidationError("Cannot independently read portable material JSON") from error
    if not isinstance(document, dict):
        raise ValidationError("GLB material JSON document must be an object")
    return document


def validate_portable_materials(path, expectation):
    """Compare actual primitive bindings with fresh native effective materials.

    Geometry/camera validation cannot detect the Blender export_apply material
    override bug. This separate reader checks every mesh node and every used
    primitive material, including modifier-generated facade details.
    """
    expected = check_material_expectations(expectation)
    document = _glb_document(path)
    nodes, meshes, materials = (document.get(key) for key in ("nodes", "meshes", "materials"))
    if not all(isinstance(records, list) for records in (nodes, meshes, materials)):
        raise ValidationError("Portable model needs explicit mesh nodes and materials")
    actual = {}
    primitives_checked = 0
    for node in nodes:
        if not isinstance(node, dict) or "mesh" not in node:
            continue
        name, mesh_index = node.get("name"), node["mesh"]
        if not isinstance(name, str) or name in actual or name not in expected or type(mesh_index) is not int or not 0 <= mesh_index < len(meshes):
            raise ValidationError("Portable mesh node inventory differs from the native material inventory")
        metadata = expectation.get("node_owner_roles")
        if metadata is not None:
            extras = node.get("extras", {})
            if not isinstance(extras, dict) or any(extras.get(key) != value for key, value in metadata[name].items()):
                raise ValidationError("Portable node owner/role differs from its native source: " + name)
        mesh = meshes[mesh_index]
        primitives = mesh.get("primitives") if isinstance(mesh, dict) else None
        if not isinstance(primitives, list) or not primitives:
            raise ValidationError("Portable mesh has no primitive material bindings: " + name)
        records = []
        for primitive in primitives:
            index = primitive.get("material") if isinstance(primitive, dict) else None
            if type(index) is not int or not 0 <= index < len(materials):
                raise ValidationError("Portable primitive is missing an explicit effective material: " + name)
            material = materials[index]
            if not isinstance(material, dict):
                raise ValidationError("Portable primitive material must be an object: " + name)
            extras, pbr = material.get("extras", {}), material.get("pbrMetallicRoughness", {})
            if not isinstance(material.get("name"), str) or not material["name"].startswith("portable:") or not isinstance(extras, dict) or not isinstance(pbr, dict):
                raise ValidationError("Portable primitive material lacks source provenance: " + name)
            records.append(_material_record({"source_material_name": extras.get("source_material_name"), "base_color_factor": pbr.get("baseColorFactor", [1, 1, 1, 1]), "facade_tint_scale": extras.get("facade_tint_scale", 1), "roughness_factor": pbr.get("roughnessFactor", 1), "metallic_factor": pbr.get("metallicFactor", 1)}))
            primitives_checked += 1
        actual[name] = _unique_materials(records)
        if len(actual[name]) != len(expected[name]) or not all(any(_same_material(record, other) for other in actual[name]) for record in expected[name]) or not all(any(_same_material(record, other) for other in expected[name]) for record in actual[name]):
            raise ValidationError("Portable primitive materials differ from fresh native effective slots: " + name)
    if set(actual) != set(expected):
        raise ValidationError("Portable material reader did not inspect every expected mesh node")
    return {"status": "passed", "scope": "distinct effective material binding sets for every mesh node and every used primitive", "mesh_nodes_checked": len(actual), "primitive_bindings_checked": primitives_checked, "native_effective_bindings_checked": sum(map(len, expected.values())), "numeric_tolerance": 1e-6, "source_material_names_checked": True, "base_color_roughness_metallic_checked": True, "modifier_effective_materials_checked": True, "per_face_material_assignment_checked": False, "node_owner_roles_checked": expectation.get("node_owner_roles") is not None, "user_accessibility": "not_verified"}


def check_model_expectations(records):
    """Reject a weak inventory which merely declares a model nonempty."""
    if not isinstance(records, dict) or set(records) != set(MODEL_NAMES):
        raise ValidationError("Fresh model-expectations.json must describe all four v3 models")
    for name, record in records.items():
        if not isinstance(record, dict) or type(record.get("objects")) is not int or record["objects"] < 15:
            raise ValidationError("Expected model needs an exact inventory including the original 15 objects: " + name)
        bounds = record.get("object_bounds")
        if not isinstance(bounds, dict) or len(bounds) != record["objects"]:
            raise ValidationError("Exact world bounds are required for every model object: " + name)
        for vectors in bounds.values():
            if not isinstance(vectors, (list, tuple)) or len(vectors) != 2 or any(len(vector) != 3 or any(type(value) not in (int, float) or not math.isfinite(value) for value in vector) for vector in vectors):
                raise ValidationError("Model bounds must contain two finite XYZ vectors: " + name)
        if type(record.get("faces")) is not int or record["faces"] < 1:
            raise ValidationError("Exact source face count is required: " + name)
        vertex_key = "vertices" if name.endswith(".blend") else "min_vertices"
        if type(record.get(vertex_key)) is not int or record[vertex_key] < 1:
            raise ValidationError("Source native vertex count / GLB minimum unique vertex count is required: " + name)
        if name.endswith(".glb"):
            check_material_expectations(record)
        cameras = record.get("camera_parameters")
        if type(record.get("cameras")) is not int or record["cameras"] != 3 or not isinstance(cameras, dict) or len(cameras) != 3:
            raise ValidationError("All three source cameras require exact parameters: " + name)
        for camera in cameras.values():
            for field in ("position", "forward", "up"):
                vector = camera.get(field)
                if not isinstance(vector, (list, tuple)) or len(vector) != 3 or any(type(value) not in (int, float) or not math.isfinite(value) for value in vector):
                    raise ValidationError("Source camera needs finite " + field + ": " + name)
            if type(camera.get("vertical_fov")) not in (int, float) or not 0 < camera["vertical_fov"] < 180:
                raise ValidationError("Source camera needs a valid vertical FOV: " + name)
    return records


def check_semantic_reports(directory):
    directory = Path(directory)
    geometry = strict_json(directory / "geometry-report.json")
    if geometry.get("synthetic") is not True or geometry.get("real_site_accuracy") is not False:
        raise ValidationError("Delivery must be explicitly synthetic and must not claim real-site accuracy")
    if geometry.get("source_meshes_preserved") != 15 or geometry.get("source_geometry_changed") != []:
        raise ValidationError("The original 15 source meshes must be preserved")
    roundtrip = strict_json(directory / "roundtrip-geometry.json")
    for name in MODEL_NAMES:
        record = roundtrip.get(name, {})
        if record.get("passed") is not True or record.get("source_objects_checked") != 15 or record.get("source_geometry_changed") != []:
            raise ValidationError("Original 15 mesh roundtrip proof is missing or failed: " + name)
    snapshots = strict_json(directory / "scene-snapshots.json")
    before, after = snapshots.get("before"), snapshots.get("after")
    if not isinstance(before, dict) or not isinstance(after, dict) or not {"__scene__", "__world__"}.issubset(before) or not {"__scene__", "__world__"}.issubset(after):
        raise ValidationError("Complete before/after scene and world snapshots are required")
    actual = compare_snapshots(before, after, "A")
    recorded = strict_json(directory / "edit-report.json")
    if actual["passed"] is not True or not actual["changed_objects"] or any(recorded.get(key) != value for key, value in actual.items()):
        raise ValidationError("Facade edit report differs from the independently recomputed scene comparison")
    checks = {"synthetic": True, "original_meshes_preserved": 15, "roundtrip_models": list(MODEL_NAMES), "targeted_edit": actual, "real_site_accuracy": False}
    portable_report_path = directory / "portable-materials-report.json"
    if portable_report_path.is_file():
        portable = strict_json(portable_report_path)
        frozen = portable.get("frozen_sources", {})
        preserved_names = set(IMAGE_NAMES) | {name for name in MODEL_NAMES if name.endswith(".blend")}
        before_hashes, after_hashes = frozen.get("before_sha256"), frozen.get("after_sha256")
        if frozen.get("unchanged") is not True or not isinstance(before_hashes, dict) or set(before_hashes) != preserved_names or before_hashes != after_hashes:
            raise ValidationError("Portable repair must preserve both native scenes and all six saved PNGs")
        if any(file_identity(directory / name)["sha256"] != sha for name, sha in before_hashes.items()):
            raise ValidationError("Current native scenes or saved images differ from frozen pre-repair hashes")
        if any(portable.get(name, {}).get("passed") is not True for name in MODEL_NAMES if name.endswith(".glb")):
            raise ValidationError("Portable material report did not pass both repaired exports")
        for name in ("model.glb", "edited-model.glb"):
            record = portable[name]
            native_name = name.removesuffix(".glb") + ".blend"
            if record.get("glb_sha256") != file_identity(directory / name)["sha256"] or record.get("native_source") != native_name or record.get("native_source_sha256") != before_hashes[native_name]:
                raise ValidationError("Portable repair report does not identify the current GLB and frozen native source: " + name)
        checks["portable_repair_preserves_frozen_native_and_images"] = True
    browser_path = directory / "browser-report.json"
    if browser_path.is_file():
        browser = strict_json(browser_path)
        if browser.get("status") != "passed" or browser.get("html_sha256") != file_identity(directory / "viewer.html")["sha256"] or browser.get("source_bytes_unchanged") is not True:
            raise ValidationError("Browser report does not prove the current unchanged viewer artifact")
        if browser.get("page_errors") != [] or browser.get("console_errors") != [] or browser.get("network_requests") != []:
            raise ValidationError("Offline browser report contains errors, unexpected requests or missing evidence")
        checks["browser_report_matches_current_viewer"] = True
    native_browser_path = directory / "native-browser-report.json"
    if native_browser_path.is_file():
        native_browser = strict_json(native_browser_path)
        if native_browser.get("status") != "passed" or native_browser.get("html_sha256") != file_identity(directory / "viewer.html")["sha256"]:
            raise ValidationError("Native browser report does not prove the current viewer artifact")
        checks["native_browser_report_matches_current_viewer"] = True
    return checks


class _ViewerPayload(HTMLParser):
    def __init__(self):
        super().__init__()
        self.active = False
        self.payload_text = ""
        self.image_data = {}

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        if tag == "script" and attributes.get("id") == "viewerPayload":
            self.active = True
        if tag == "img" and attributes.get("id"):
            self.image_data[attributes["id"]] = attributes.get("src", "")

    def handle_data(self, data):
        if self.active:
            self.payload_text += data

    def handle_endtag(self, tag):
        if tag == "script":
            self.active = False


def validate_embedded_viewer(path, source_models, source_images):
    """Read and independently import the viewer's actual embedded bytes."""
    parser = _ViewerPayload()
    parser.feed(Path(path).read_text(encoding="utf-8"))
    try:
        payload = json.loads(parser.payload_text)
    except (ValueError, TypeError) as error:
        raise ValidationError("Viewer has no valid independent embedded payload") from error
    if payload.get("synthetic") is not True or payload.get("version") != "architectural-v3":
        raise ValidationError("Viewer must identify the explicitly synthetic v3 proposal")
    models, images = payload.get("models"), payload.get("images")
    if not isinstance(models, list) or {item.get("name") for item in models} != {"model.glb", "edited-model.glb"} or len(models) != 2:
        raise ValidationError("Viewer must embed exactly the current baseline and edited GLBs")
    if not isinstance(images, list) or {item.get("name") for item in images} != set(IMAGE_NAMES[:4]) or len(images) != 4:
        raise ValidationError("Viewer must identify all four current render PNGs")
    receipts = []
    with tempfile.TemporaryDirectory(prefix="golden-v3-embedded-check-") as temp:
        for record in images + models:
            name = safe_name(record.get("name"))
            if name.endswith(".png"):
                data_url = parser.image_data.get(record.get("id"), "")
                if not data_url.startswith("data:image/png;base64,"):
                    raise ValidationError("Viewer PNG is missing or has an unsupported encoding: " + name)
                encoded = data_url.split(",", 1)[1]
                expected = source_images[name]
            else:
                expected = source_models[name]
            if name.endswith(".png"):
                try:
                    content = base64.b64decode(encoded, validate=True)
                except (ValueError, TypeError) as error:
                    raise ValidationError("Viewer embedded bytes are not valid base64: " + name) from error
            else:
                content = decode_embedded_model(record, payload)
            if len(content) != expected["bytes"] or hashlib.sha256(content).hexdigest() != expected["sha256"] or any(record.get(key) != expected[key] for key in ("bytes", "sha256")):
                raise ValidationError("Viewer embedded bytes differ from the current source artifact: " + name)
            temporary = Path(temp) / name
            temporary.write_bytes(content)
            evidence = validate_file(temporary, expected=expected, artifact_role="v3_viewer_embedded_source")
            if name.endswith(".glb"):
                evidence["portable_material_validation"] = validate_portable_materials(temporary, expected)
            evidence.pop("path", None)
            receipts.append(evidence)
    return {"status": "passed", "embedded_sources": receipts, "user_accessibility": "not_verified"}


def decode_embedded_model(record, payload):
    """Reassemble exact raw GLB bytes, including shared unmodified BIN chunks."""
    encoding = record.get("encoding", "base64")
    try:
        if encoding == "base64":
            content = base64.b64decode(record.get("base64", ""), validate=True)
        elif encoding == "glb_shared_bin":
            header = base64.b64decode(record.get("header_base64", ""), validate=True)
            json_chunk = base64.b64decode(record.get("json_chunk_base64", ""), validate=True)
            binary_chunk = base64.b64decode(payload.get("shared_glb_bin_base64", ""), validate=True)
            if len(header) != 12 or len(json_chunk) < 8 or len(binary_chunk) < 8:
                raise ValidationError("Shared-BIN model chunks are incomplete")
            magic, version, total = struct.unpack("<4sII", header)
            json_length, json_kind = struct.unpack("<II", json_chunk[:8])
            bin_length, bin_kind = struct.unpack("<II", binary_chunk[:8])
            if magic != b"glTF" or version != 2 or json_kind != 0x4E4F534A or bin_kind != 0x004E4942 or json_length % 4 or bin_length % 4 or json_length + 8 != len(json_chunk) or bin_length + 8 != len(binary_chunk):
                raise ValidationError("Shared-BIN model headers/chunks are invalid")
            content = header + json_chunk + binary_chunk
            if total != len(content):
                raise ValidationError("Shared-BIN model reconstructed length differs from source header")
        else:
            raise ValidationError("Unsupported embedded model encoding: " + str(encoding))
    except (ValueError, TypeError, struct.error) as error:
        raise ValidationError("Viewer embedded GLB encoding is invalid") from error
    if len(content) != record.get("bytes") or hashlib.sha256(content).hexdigest() != record.get("sha256"):
        raise ValidationError("Viewer embedded model raw hash differs from its declared source")
    return content


def _record(path, expectations=None):
    return {**(expectations or {}), "name": Path(path).name, **file_identity(path)}


